#!/usr/bin/env node
// Reads .env.local and writes config.local.js — a plain script the extension
// can load via importScripts() (service workers can't read the filesystem
// directly, so this is the bridge). Re-run after editing .env.local, then
// reload the extension in chrome://extensions.

const fs = require("fs");
const path = require("path");

const ENV_PATH = path.join(__dirname, ".env.local");
const OUT_PATH = path.join(__dirname, "config.local.js");

const KEYS = ["ANTHROPIC_API_KEY", "FASHN_API_KEY", "FAL_API_KEY"];

// Accepts common naming variants (case, underscores, "claude" vs
// "anthropic") so this works whether .env.local uses the exact canonical
// names or a shorthand like `fashn_api` / `claude_api` / `fal_api`.
const ALIASES = {
  ANTHROPIC_API_KEY: ["anthropicapikey", "anthropicapi", "claudeapikey", "claudeapi", "claude"],
  FASHN_API_KEY: ["fashnapikey", "fashnapi", "fashn"],
  FAL_API_KEY: ["falapikey", "falapi", "fal"],
};

function normalize(key) {
  return key.toLowerCase().replace(/[^a-z0-9]/g, "");
}

function parseEnvFile(text) {
  const values = {};
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const rawKey = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    // Strip matching surrounding quotes, if present.
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!value) continue;

    const normalized = normalize(rawKey);
    const canonicalKey = KEYS.find(
      (k) => normalize(k) === normalized || (ALIASES[k] || []).includes(normalized)
    );
    if (canonicalKey) values[canonicalKey] = value;
  }
  return values;
}

if (!fs.existsSync(ENV_PATH)) {
  console.error(
    `No .env.local found at ${ENV_PATH}\n` +
      `Copy .env.local.example to .env.local, fill in your keys, then re-run this script.`
  );
  process.exit(1);
}

const config = parseEnvFile(fs.readFileSync(ENV_PATH, "utf8"));
for (const key of KEYS) {
  if (!config[key]) config[key] = "";
}

const missing = KEYS.filter((k) => !config[k]);

const output =
  `// AUTO-GENERATED by sync-keys.js from .env.local — do not edit directly,\n` +
  `// and do not commit this file (it's gitignored).\n` +
  `self.FIT_FOR_ME_CONFIG = ${JSON.stringify(config, null, 2)};\n`;

fs.writeFileSync(OUT_PATH, output);

console.log(`Wrote ${OUT_PATH}`);
if (missing.length) {
  console.log(`Note: still blank in .env.local: ${missing.join(", ")}`);
}
console.log("Now reload the extension in chrome://extensions.");
